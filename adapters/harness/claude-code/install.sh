#!/usr/bin/env bash
# install.sh <repo-path>      Claude Code harness for one repo. Safe to re-run (run it again after
#                             updating the kit: the command and subagent files are regenerated).
# Writes into the repo:
#   .claude/settings.local.json   machine-local (git-ignored): ADLC_KIT + guard and session hooks
#   .claude/commands/<name>.md    slash commands, generated from core/playbooks/
#   .claude/agents/<role>.md      subagents, generated from core/roles/
#   CLAUDE.md                     gets one line: @AGENTS.md (only if it does not import it yet)
# Subagent models come from ROLE_* in the repo's .adlc/config.env (empty = Claude Code's default).
set -euo pipefail
H="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; KIT="$(cd "$H/../../.." && pwd)"
REPO="$(cd "${1:?usage: install.sh <repo-path>}" && pwd)"
mark="<!-- Generated by adlc-kit (adapters/harness/claude-code/install.sh). Do not edit: change the kit and re-run. -->"
role_model() { [ "$1" = "-" ] && return; sed -n "s/^$1=\"\([^\"]*\)\".*/\1/p" "$REPO/.adlc/config.env" 2>/dev/null | head -1; }

python3 "$H/merge_settings.py" "$REPO/.claude/settings.local.json" "$KIT"
touch "$REPO/.gitignore"
grep -qxF ".claude/settings.local.json" "$REPO/.gitignore" || echo ".claude/settings.local.json" >> "$REPO/.gitignore"

mkdir -p "$REPO/.claude/commands" "$REPO/.claude/agents"
while IFS=$'\t' read -r name desc hint; do
  out="$REPO/.claude/commands/$name.md"
  if [ -f "$out" ] && ! grep -qF "Generated by adlc-kit" "$out"; then echo "  ⚠ $out exists and is not from the kit: left alone"; continue; fi
  { printf -- '---\ndescription: %s\nargument-hint: %s\n---\n%s\n\nInput: $ARGUMENTS\n\n' "$desc" "$(printf '%s' "$hint" | python3 -c 'import json,sys;print(json.dumps(sys.stdin.read()))')" "$mark"
    cat "$KIT/core/playbooks/$name.md"; printf '\n'; cat "$H/NOTES.md"; } > "$out"
done < "$H/commands.tsv"
echo "  wrote .claude/commands/ ($(wc -l < "$H/commands.tsv" | tr -d ' ') commands)"

while IFS=$'\t' read -r name desc tools role; do
  out="$REPO/.claude/agents/$name.md"
  if [ -f "$out" ] && ! grep -qF "Generated by adlc-kit" "$out"; then echo "  ⚠ $out exists and is not from the kit: left alone"; continue; fi
  model="$(role_model "$role")"
  { printf -- '---\nname: %s\ndescription: %s\ntools: %s\n' "$name" "$desc" "$tools"
    [ -z "$model" ] || printf 'model: %s\n' "$model"
    printf -- '---\n%s\n\n' "$mark"; cat "$KIT/core/roles/$name.md"; } > "$out"
done < "$H/agents.tsv"
echo "  wrote .claude/agents/ ($(wc -l < "$H/agents.tsv" | tr -d ' ') subagents)"

if [ ! -f "$REPO/CLAUDE.md" ]; then printf '@AGENTS.md\n' > "$REPO/CLAUDE.md"; echo "  created CLAUDE.md (imports AGENTS.md)"
elif ! grep -q '@AGENTS.md' "$REPO/CLAUDE.md"; then printf '\n@AGENTS.md\n' >> "$REPO/CLAUDE.md"; echo "  CLAUDE.md += @AGENTS.md"; fi
echo "  Claude Code harness ready. Commit .claude/commands, .claude/agents and CLAUDE.md; restart Claude Code in this repo."
